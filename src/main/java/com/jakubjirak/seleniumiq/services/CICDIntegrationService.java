package com.jakubjirak.seleniumiq.services;

import com.intellij.openapi.application.ApplicationManager;
import com.intellij.openapi.components.Service;

import java.util.*;

@Service(Service.Level.APP)
public final class CICDIntegrationService {

    public static CICDIntegrationService getInstance() {
        return ApplicationManager.getApplication().getService(CICDIntegrationService.class);
    }

    public enum CIProvider {
        JENKINS, GITHUB_ACTIONS, GITLAB_CI, CIRCLE_CI, AZURE_DEVOPS, BAMBOO, TEAMCITY
    }

    public String generateJenkinsPipeline(String projectName, Map<String, Object> config) {
        StringBuilder pipeline = new StringBuilder();
        
        pipeline.append("// Generated by SeleniumIQ - Enterprise Feature\n");
        pipeline.append("pipeline {\n");
        pipeline.append("    agent any\n\n");
        
        pipeline.append("    environment {\n");
        pipeline.append("        SELENIUM_VERSION = '4.16.1'\n");
        pipeline.append("        JAVA_HOME = '/usr/lib/jvm/java-17'\n");
        pipeline.append("    }\n\n");
        
        pipeline.append("    stages {\n");
        pipeline.append("        stage('Checkout') {\n");
        pipeline.append("            steps {\n");
        pipeline.append("                git branch: 'main', url: '").append(config.get("repo_url")).append("'\n");
        pipeline.append("            }\n");
        pipeline.append("        }\n\n");
        
        pipeline.append("        stage('Build') {\n");
        pipeline.append("            steps {\n");
        pipeline.append("                sh 'mvn clean compile'\n");
        pipeline.append("            }\n");
        pipeline.append("        }\n\n");
        
        pipeline.append("        stage('Run Selenium Tests') {\n");
        pipeline.append("            steps {\n");
        pipeline.append("                sh 'mvn test -Dtest=**/*Test'\n");
        pipeline.append("            }\n");
        pipeline.append("        }\n\n");
        
        pipeline.append("        stage('Generate Report') {\n");
        pipeline.append("            steps {\n");
        pipeline.append("                junit '**/target/surefire-reports/*.xml'\n");
        pipeline.append("                publishHTML([\n");
        pipeline.append("                    reportDir: 'target/surefire-reports',\n");
        pipeline.append("                    reportFiles: 'index.html',\n");
        pipeline.append("                    reportName: 'Test Report'\n");
        pipeline.append("                ])\n");
        pipeline.append("            }\n");
        pipeline.append("        }\n");
        pipeline.append("    }\n\n");
        
        pipeline.append("    post {\n");
        pipeline.append("        always {\n");
        pipeline.append("            archiveArtifacts artifacts: '**/target/*.jar', fingerprint: true\n");
        pipeline.append("        }\n");
        pipeline.append("        failure {\n");
        pipeline.append("            emailext(\n");
        pipeline.append("                subject: \"Failed: ").append(projectName).append(" - Build #${BUILD_NUMBER}\",\n");
        pipeline.append("                body: \"Check console output at ${BUILD_URL}\",\n");
        pipeline.append("                to: '").append(config.getOrDefault("notification_email", "team@example.com")).append("'\n");
        pipeline.append("            )\n");
        pipeline.append("        }\n");
        pipeline.append("    }\n");
        pipeline.append("}\n");
        
        return pipeline.toString();
    }

    public String generateGitHubActions(String projectName, Map<String, Object> config) {
        StringBuilder workflow = new StringBuilder();
        
        workflow.append("# Generated by SeleniumIQ - Enterprise Feature\n");
        workflow.append("name: Selenium Tests\n\n");
        
        workflow.append("on:\n");
        workflow.append("  push:\n");
        workflow.append("    branches: [ main, develop ]\n");
        workflow.append("  pull_request:\n");
        workflow.append("    branches: [ main ]\n\n");
        
        workflow.append("jobs:\n");
        workflow.append("  test:\n");
        workflow.append("    runs-on: ubuntu-latest\n\n");
        
        workflow.append("    strategy:\n");
        workflow.append("      matrix:\n");
        workflow.append("        browser: [chrome, firefox]\n\n");
        
        workflow.append("    steps:\n");
        workflow.append("    - uses: actions/checkout@v3\n\n");
        
        workflow.append("    - name: Set up JDK 17\n");
        workflow.append("      uses: actions/setup-java@v3\n");
        workflow.append("      with:\n");
        workflow.append("        java-version: '17'\n");
        workflow.append("        distribution: 'temurin'\n\n");
        
        workflow.append("    - name: Cache Maven packages\n");
        workflow.append("      uses: actions/cache@v3\n");
        workflow.append("      with:\n");
        workflow.append("        path: ~/.m2\n");
        workflow.append("        key: ${{ runner.os }}-m2-${{ hashFiles('**/pom.xml') }}\n\n");
        
        workflow.append("    - name: Run Selenium Tests\n");
        workflow.append("      run: mvn test -Dbrowser=${{ matrix.browser }}\n\n");
        
        workflow.append("    - name: Upload Test Results\n");
        workflow.append("      if: always()\n");
        workflow.append("      uses: actions/upload-artifact@v3\n");
        workflow.append("      with:\n");
        workflow.append("        name: test-results-${{ matrix.browser }}\n");
        workflow.append("        path: target/surefire-reports\n\n");
        
        workflow.append("    - name: Publish Test Report\n");
        workflow.append("      uses: dorny/test-reporter@v1\n");
        workflow.append("      if: always()\n");
        workflow.append("      with:\n");
        workflow.append("        name: Test Results\n");
        workflow.append("        path: target/surefire-reports/*.xml\n");
        workflow.append("        reporter: java-junit\n");
        
        return workflow.toString();
    }

    public String generateGitLabCI(String projectName, Map<String, Object> config) {
        StringBuilder ci = new StringBuilder();
        
        ci.append("# Generated by SeleniumIQ - Enterprise Feature\n\n");
        
        ci.append("image: maven:3.8-openjdk-17\n\n");
        
        ci.append("variables:\n");
        ci.append("  MAVEN_OPTS: \"-Dmaven.repo.local=.m2/repository\"\n\n");
        
        ci.append("cache:\n");
        ci.append("  paths:\n");
        ci.append("    - .m2/repository\n\n");
        
        ci.append("stages:\n");
        ci.append("  - build\n");
        ci.append("  - test\n");
        ci.append("  - report\n\n");
        
        ci.append("build:\n");
        ci.append("  stage: build\n");
        ci.append("  script:\n");
        ci.append("    - mvn clean compile\n\n");
        
        ci.append("test:chrome:\n");
        ci.append("  stage: test\n");
        ci.append("  script:\n");
        ci.append("    - mvn test -Dbrowser=chrome\n");
        ci.append("  artifacts:\n");
        ci.append("    when: always\n");
        ci.append("    reports:\n");
        ci.append("      junit: target/surefire-reports/TEST-*.xml\n\n");
        
        ci.append("test:firefox:\n");
        ci.append("  stage: test\n");
        ci.append("  script:\n");
        ci.append("    - mvn test -Dbrowser=firefox\n");
        ci.append("  artifacts:\n");
        ci.append("    when: always\n");
        ci.append("    reports:\n");
        ci.append("      junit: target/surefire-reports/TEST-*.xml\n\n");
        
        ci.append("report:\n");
        ci.append("  stage: report\n");
        ci.append("  script:\n");
        ci.append("    - echo \"Tests completed\"\n");
        ci.append("  only:\n");
        ci.append("    - main\n");
        
        return ci.toString();
    }

    public String generateCircleCI(String projectName) {
        StringBuilder config = new StringBuilder();
        
        config.append("# Generated by SeleniumIQ - Enterprise Feature\n");
        config.append("version: 2.1\n\n");
        
        config.append("orbs:\n");
        config.append("  maven: circleci/maven@1.4.0\n\n");
        
        config.append("jobs:\n");
        config.append("  test:\n");
        config.append("    docker:\n");
        config.append("      - image: cimg/openjdk:17.0\n");
        config.append("    steps:\n");
        config.append("      - checkout\n");
        config.append("      - restore_cache:\n");
        config.append("          keys:\n");
        config.append("            - v1-dependencies-{{ checksum \"pom.xml\" }}\n");
        config.append("      - run: mvn test\n");
        config.append("      - save_cache:\n");
        config.append("          paths:\n");
        config.append("            - ~/.m2\n");
        config.append("          key: v1-dependencies-{{ checksum \"pom.xml\" }}\n");
        config.append("      - store_test_results:\n");
        config.append("          path: target/surefire-reports\n\n");
        
        config.append("workflows:\n");
        config.append("  test_workflow:\n");
        config.append("    jobs:\n");
        config.append("      - test\n");
        
        return config.toString();
    }

    public Map<String, String> generateCITemplates(CIProvider provider, String projectName) {
        Map<String, String> templates = new HashMap<>();
        Map<String, Object> defaultConfig = new HashMap<>();
        defaultConfig.put("repo_url", "https://github.com/example/repo.git");
        defaultConfig.put("notification_email", "team@example.com");
        
        switch (provider) {
            case JENKINS:
                templates.put("Jenkinsfile", generateJenkinsPipeline(projectName, defaultConfig));
                break;
            case GITHUB_ACTIONS:
                templates.put(".github/workflows/tests.yml", generateGitHubActions(projectName, defaultConfig));
                break;
            case GITLAB_CI:
                templates.put(".gitlab-ci.yml", generateGitLabCI(projectName, defaultConfig));
                break;
            case CIRCLE_CI:
                templates.put(".circleci/config.yml", generateCircleCI(projectName));
                break;
            default:
                templates.put("README.md", "# CI/CD Integration\nComing soon for " + provider);
        }
        
        return templates;
    }
}
